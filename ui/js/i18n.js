const dicts = { en, tr };
let lang = 'en';

export function setLanguage(pref) {
  if (pref && pref !== 'auto' && dicts[pref]) lang = pref;
  else lang = (navigator.language || 'en').toLowerCase().startsWith('tr') ? 'tr' : 'en';
  document.documentElement.lang = lang;
}

export function currentLanguage() { return lang; }

export function t(key, vars) {
  let s = (dicts[lang] && dicts[lang][key]) || en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

